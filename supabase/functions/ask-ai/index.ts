import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          {
            role: "system",
            content: `You are the AI concierge for CoupleOfHours.com — a platform that lets travelers book premium hotel rooms by the hour in New York City, Brooklyn, Queens, The Bronx, Staten Island, and New Jersey (Jersey City, Hoboken, Newark).

Key facts you know:
- Hourly rates start from $10/hr, typical range $18-$45/hr
- Available areas: Manhattan, Brooklyn, Queens, The Bronx, Staten Island, Jersey City, Hoboken, Newark
- Airports served: JFK, LaGuardia (LGA), Newark (EWR)
- Time slots: 6am-12pm, 11am-5pm, 1pm-7pm, 5pm-11pm
- All hotels are verified, offer free cancellation, and instant booking
- Popular amenities: WiFi, Pool, Spa, Gym, Rooftop Bar, City View, Room Service
- Great for: couples, layovers, business travelers, day rest, freshening up

Be helpful, concise, and friendly. Recommend specific areas or price ranges when asked. If users ask about things outside the platform, politely redirect to hourly hotel booking topics. Use emoji sparingly for warmth.`
          },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please try again later." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI service temporarily unavailable." }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("ask-ai error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
